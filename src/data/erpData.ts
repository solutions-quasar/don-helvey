export function loadErpLeads(): ErpLeadItem[] {
  try {
    const raw = localStorage.getItem(ERP_LEADS_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(ERP_LEADS_STORAGE_KEY, JSON.stringify(INITIAL_ERP_LEADS));
      return INITIAL_ERP_LEADS;
    }
    return JSON.parse(raw);
  } catch {
    return INITIAL_ERP_LEADS;
  }
}

export function saveErpLeads(leads: ErpLeadItem[]): void {
  try {
    localStorage.setItem(ERP_LEADS_STORAGE_KEY, JSON.stringify(leads));
  } catch (e) {
    console.error('Failed saving ERP leads to localStorage:', e);
  }
}

export function addWebsiteLeadToErp(params: {
  fullName: string;
  phone: string;
  concernType: string;
  city?: string;
}): ErpLeadItem {
  const existing = loadErpLeads();
  const newLead: ErpLeadItem = {
    id: `LD-${Math.floor(910 + Math.random() * 890)}`,
    fullName: params.fullName,
    phone: params.phone,
    email: 'Submitted via Quick Form',
    address: params.city ? `${params.city}, GA Property` : 'North Atlanta / North GA Property',
    city: params.city || 'Cumming',
    concernType: params.concernType || 'Visible Mold',
    foundation: 'Crawl Space',
    yearBuilt: 2001,
    stage: 'New Lead',
    source: 'Website Form',
    createdAt: 'Just Now',
    notes: `New quick website inquiry (${params.concernType}). Call homeowner directly at ${params.phone}.`,
    estimatedJobValue: 4500,
    donCommissionRate: 0.15,
    moldTrustJobType: 'Pending Don’s On-Site Moisture Evaluation',
  };
  const updated = [newLead, ...existing];
  saveErpLeads(updated);
  return newLead;
}

